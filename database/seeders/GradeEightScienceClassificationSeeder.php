    private function choice(string $title, string $question, array $options, string $answer): array
    {
        return $this->block('multiple_choice', $title, [
            'emoji' => '✅',
            'question' => $question,
            'options_text' => implode("\n", $options),
            'answer' => $answer,
            'hint' => 'ارجع إلى الشرح وحدد الكلمة العلمية الأساسية في السؤال.',
            'score' => 5,
        ], true);
    }

    private function trueFalse(string $title, string $statement, bool $answer): array
    {
        return $this->block('true_false', $title, [
            'emoji' => '🧪',
            'question' => $statement,
            'options_text' => "صحيح\nخطأ",
            'answer' => $answer ? 'صحيح' : 'خطأ',
            'hint' => 'اسأل نفسك: هل العبارة تنطبق على المفهوم العلمي كما ورد في الشرح؟',
            'score' => 4,
        ], true);
    }

    private function matching(string $title, string $question, array $pairs): array
    {
        return $this->block('match_term', $title, [
            'emoji' => '🔗',
            'question' => $question,
            'left_items_text' => implode("\n", array_keys($pairs)),
            'right_items_text' => implode("\n", array_values($pairs)),
            'hint' => 'اختر المفهوم أولاً، ثم اربطه بالوصف العلمي الدقيق.',
            'score' => 8,
        ], true);
    }

    private function block(string $type, string $title, array $content, bool $graded = false): array
    {
        $media = [
            'image_url' => $content['image_url'] ?? '',
            'image_alt' => $content['image_alt'] ?? '',
            'video_url' => $content['video_url'] ?? '',
            'pdf_url' => $content['pdf_url'] ?? '',
            'audio_url' => $content['audio_url'] ?? '',
            'file_name' => $content['file_name'] ?? '',
        ];

        foreach (array_keys($media) as $key) {
            unset($content[$key]);
        }

        return [
            'type' => $type,
            'category' => $this->category($type),
            'subtype' => $this->subtype($type),
            'title' => $title,
            'content' => array_merge([
                'emoji' => $content['emoji'] ?? '✨',
                'score' => $content['score'] ?? 1,
            ], $content),
            'media' => $media,
            'settings' => [
                'demo' => true,
                'source' => self::SOURCE,
                'stage' => 'upper',
            ],
            'is_graded' => $graded,
        ];
    }

    private function category(string $type): string
    {
        if (str_contains($type, 'match') || str_contains($type, 'choice') || str_contains($type, 'true_false')) {
            return 'interactive';
        }

        return 'explanation';
    }

    private function subtype(string $type): string
    {
        if (str_contains($type, 'match')) {
            return 'matching';
        }

        if (str_contains($type, 'choice') || str_contains($type, 'true_false')) {
            return 'choice';
        }

        if (str_contains($type, 'experiment')) {
            return 'steps';
        }

        if (str_contains($type, 'concept')) {
            return 'vocabulary';
        }

        return 'explanation';
    }
